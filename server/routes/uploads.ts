import { Router, Request, Response } from 'express';
import multer from 'multer';
import path from 'path';
import fs from 'fs';
import { requireAuth } from '../auth.js';

export const uploadsRouter = Router();

const UPLOAD_DIR = path.resolve(process.cwd(), 'uploads');
if (!fs.existsSync(UPLOAD_DIR)) {
  fs.mkdirSync(UPLOAD_DIR, { recursive: true });
}

// Multer storage
const storage = multer.diskStorage({
  destination: (_req, _file, cb) => {
    cb(null, UPLOAD_DIR);
  },
  filename: (_req, file, cb) => {
    // Sanitize and append timestamp
    const safeName = file.originalname.replace(/[^a-zA-Z0-9.-]/g, '_');
    const unique = `${Date.now()}-${safeName}`;
    cb(null, unique);
  },
});

// File filter (documents, pdf, zip, code, images only)
const fileFilter = (_req: Request, file: Express.Multer.File, cb: multer.FileFilterCallback) => {
  const allowedExtensions = ['.pdf', '.doc', '.docx', '.txt', '.zip', '.tar', '.gz', '.png', '.jpg', '.jpeg', '.py', '.js', '.ts', '.java', '.cpp', '.sql'];
  const ext = path.extname(file.originalname).toLowerCase();
  if (allowedExtensions.includes(ext)) {
    cb(null, true);
  } else {
    cb(new Error(`File type ${ext} is not allowed. Permitted types: ${allowedExtensions.join(', ')}`));
  }
};

const upload = multer({
  storage,
  limits: { fileSize: 15 * 1024 * 1024 }, // 15MB limit
  fileFilter,
});

// POST /api/v1/uploads
uploadsRouter.post('/', requireAuth, upload.single('file'), (req: Request, res: Response): void => {
  if (!req.file) {
    res.status(400).json({ error: 'No file was uploaded.' });
    return;
  }

  res.json({
    message: 'File uploaded successfully',
    fileName: req.file.originalname,
    storedName: req.file.filename,
    filePath: `/api/v1/uploads/download/${req.file.filename}`,
    size: req.file.size,
  });
});

// GET /api/v1/uploads/download/:filename
uploadsRouter.get('/download/:filename', requireAuth, (req: Request, res: Response): void => {
  const safeFilename = path.basename(req.params.filename);
  const targetPath = path.join(UPLOAD_DIR, safeFilename);

  if (!fs.existsSync(targetPath)) {
    // If not found in physical folder, send a sample text placeholder
    res.setHeader('Content-Type', 'text/plain');
    res.setHeader('Content-Disposition', `attachment; filename="${safeFilename}"`);
    res.send(`SSMS Academic Document - ${safeFilename}\nGenerated by Smart Student Management System.`);
    return;
  }

  res.download(targetPath, safeFilename);
});
